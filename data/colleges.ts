const getRating = (seed: number): Rating => {
  const base = 4.0 + (seed % 10) * 0.1;
  const round2 = (n: number) => Math.round(n * 10) / 10;
  return {
    overall: round2(base),
    academics: round2(3.8 + (seed % 12) * 0.1),
    infrastructure: round2(3.7 + (seed % 13) * 0.1),
    placements: round2(3.9 + (seed % 11) * 0.1),
    faculty: round2(3.8 + (seed % 12) * 0.1),
    reviewsCount: 100 + (seed * 47) % 2500,
  };
};

const getCourses = (seed: number, feeBase: number): Course[] => {
  const count = 2 + (seed % 3);
  const indices = [0, 1, 2, 3, 4, 5, 6, 7].sort(() => (seed % 5) - 2).slice(0, count);
  return indices.map((i) => ({
    ...commonCourses[i],
    id: `${commonCourses[i].id}-${seed}`,
    fees: Math.round((commonCourses[i].fees * (0.5 + (feeBase % 100) * 0.01)) / 10000) * 10000,
  }));
};

